"""Question pool for ITD 140 quiz 2: features, preprocessing, validation and dimensionality.

Built by build_itd140_quiz2.py. Every question is written from scratch from the topic list;
scenarios, numbers and wording are original.

mc(category, question, correct, [wrong, wrong, wrong], explanation)
The right answer is slotted into a rotating position; the quiz page shuffles at run time anyway.
"""

_n = [0]


def mc(cat, q, correct, wrongs, expl):
    assert len(wrongs) == 3, q
    pos = _n[0] % 4
    _n[0] += 1
    opts = list(wrongs)
    opts.insert(pos, correct)
    return {"type": "mc", "category": cat, "question": q, "options": opts,
            "correct": pos, "explanation": expl}


def tf(cat, q, ans, expl):
    return {"type": "tf", "category": cat, "question": q, "correct": ans, "explanation": expl}


def mt(cat, q, pairs, expl=None):
    d = {"type": "matching", "category": cat, "question": q,
         "pairs": [{"left": a, "right": b} for a, b in pairs]}
    if expl:
        d["explanation"] = expl
    return d


def fb(cat, q, answers, expl):
    return {"type": "fill_blank", "category": cat, "question": q, "answers": answers,
            "explanation": expl}


def sa(cat, q, model, rubric):
    return {"type": "short_answer", "category": cat, "question": q, "answerLang": None,
            "modelAnswer": model, "rubric": rubric}


