_n = [0]


def mc(cat, q, correct, wrongs, expl):
    assert len(wrongs) == 3, q
    pos = _n[0] % 4
    _n[0] += 1
    opts = list(wrongs)
    opts.insert(pos, correct)
    return {"type": "mc", "category": cat, "question": q, "options": opts,
            "correct": pos, "explanation": expl}


def tf(cat, q, ans, expl):
    return {"type": "tf", "category": cat, "question": q, "correct": ans, "explanation": expl}


def mt(cat, q, pairs, expl=None):
    d = {"type": "matching", "category": cat, "question": q,
         "pairs": [{"left": a, "right": b} for a, b in pairs]}
    if expl:
        d["explanation"] = expl
    return d


def fb(cat, q, answers, expl):
    return {"type": "fill_blank", "category": cat, "question": q, "answers": answers,
            "explanation": expl}


