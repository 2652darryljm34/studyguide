def _rows(sql):
    if _db[0] is None:
        here = os.path.dirname(os.path.abspath(__file__))
        db = sqlite3.connect(":memory:")
        with open(os.path.join(here, "..", "data", "harborview.sql"), encoding="utf-8") as fh:
            db.executescript(fh.read())
        _db[0] = db
    return len(_db[0].execute(sql).fetchall())


